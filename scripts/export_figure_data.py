METRICS = [("rmsse", "RMSSE"), ("wrmsse", "WRMSSE"), ("mase", "MASE"), ("wape", "WAPE")]
SYSTEMS = [
    ("seasonal_naive", "S-Naive"),
    ("lightgbm", "LightGBM"),
    ("chronos2_target", "Chronos-2"),
    ("ScaleRAG_gated", "ScaleRAG"),
]


def metrics(w: Writer) -> None:
    """The M5 held-out test panel: four metrics, four systems, and who leads each."""
    d = _load("docs/scalerag-heldout-test-tables.json")["test"]["methods"]
    winners = []
    for mi, (key, _) in enumerate(METRICS):
        vals = [d[s][key] for s, _ in SYSTEMS]
        best = int(np.argmin(vals))
        winners.append(SYSTEMS[best][1])
        # Systems are laid out top to bottom in SYSTEMS order, so the y
        # coordinate counts down from the top rather than up from the axis.
        # split rather than overlaid: an overlaid best-bar would print its
        # value twice, once from each series
        w.table(
            f"metric{mi}",
            ["y", "v"],
            [[len(SYSTEMS) - 1 - si, f"{v:.6f}"] for si, v in enumerate(vals) if si != best],
        )
        w.table(f"metric{mi}best", ["y", "v"], [[len(SYSTEMS) - 1 - best, f"{vals[best]:.6f}"]])
    # The figure's whole argument is that the ranking reorders, so assert it does.
    if len(set(winners)) == 1:
        raise ValueError(
            f"one system leads every metric ({winners[0]}); the figure claims otherwise"
        )
    w.macros(
        "metrics",
        {f"SGwinner{chr(65 + i)}": n for i, n in enumerate(winners)}
        | {f"SGlabel{chr(65 + i)}": lab for i, (_, lab) in enumerate(METRICS)}
        | {f"SGsys{chr(65 + i)}": lab for i, (_, lab) in enumerate(SYSTEMS)},
    )
    w.say(
        "metrics: leaders "
        + ", ".join(f"{m[1]}={n}" for m, n in zip(METRICS, winners, strict=True))
    )


# --------------------------------------------------------------- fig_ablation
def ablation(w: Writer) -> None:
    """Per-channel ETTm2 retrieval MSE, raw against restored, at the deployed k."""
    j = _load("reports/phase11a/scalerag_native_ettm2_test.json")
    names = j["variables"]
    z = np.load(REPO / "reports/phase11a/scalerag_native_ettm2_test_preds.npz")
    trues, var_of = z["trues"], z["var_of"]
    raw, res = z["raw_mean_20"], z["res_mean_20"]

    per, improved = [], 0
    for vi, nm in enumerate(names):
        m = var_of == vi
        r = float(np.mean((raw[m] - trues[m]) ** 2))
        s = float(np.mean((res[m] - trues[m]) ** 2))
        improved += int(s < r)
        per.append((nm, r, s))
    # worst raw error at the top, so the panel reads as a ranking
    per.sort(key=lambda t: t[1])
    rows = [[i, f"{r:.6f}", f"{s:.6f}"] for i, (_, r, s) in enumerate(per)]

    # Pooled MSE must reproduce the recorded k=20 entry, or these are not the
    # arrays the reported result was computed from.
    def rec(block: str) -> float:
        return next(e["mse"] for e in j[block] if e["scale"] == "mean" and e["k"] == 20)

    for got, want, lab in (
        (float(np.mean((raw - trues) ** 2)), rec("scalerag_raw_retrieval"), "raw"),
        (float(np.mean((res - trues) ** 2)), rec("scalerag_restored_retrieval"), "restored"),
    ):
        if abs(got - want) > 1e-4:
            raise ValueError(f"{lab} pooled MSE {got:.6f} disagrees with the recorded {want:.6f}")

    w.table("ablation", ["i", "raw", "restored"], rows)
    # dumbbell connectors: one two-point path per channel, blank-line separated,
    # read back under `empty line=jump'
    if not w.check:
        seg = "x  y\n" + "\n\n".join(
            f"{r:.6f}  {i}\n{s:.6f}  {i}" for i, (_, r, s) in enumerate(per)
        )
        (OUT / "ablationlink.dat").write_text(seg + "\n")
        # channel names, generated rather than retyped, so the labels cannot
        # drift out of step with the rows above
        (OUT / "ablationnames.tex").write_text(
            "% generated by scripts/export_figure_data.py -- do not edit\n"
            "\\pgfplotsset{ablnames/.style={ytick={"
            + ",".join(str(i) for i in range(len(per)))
            + "}, yticklabels={"
            + ",".join(nm for nm, _, _ in per)
            + "}}}\n"
        )

    # The M5 companion deliberately carries three marks, not two.  Raw
    # retrieval on M5 is only 2% off the deployed branch, so a two-point
    # raw-vs-restored panel would understate what restoration does; the
    # decisive contrast is the normalised-but-unrestored ablation, which is
    # 3.8x worse than either.  Panel (a) and panel (b) therefore contrast
    # different things and the figure has to say so.
    m5 = _load("docs/scalerag-final-tables.json")["m5_1000"]
    m5_raw = m5["methods_rmsse"]["retrieval_raw"]
    m5_norm = m5["key_ablations"]["norm_no_restore"]
    m5_res = m5["methods_rmsse"]["retrieval_scaleaware_P5"]
    w.table("ablationm5raw", ["x", "y"], [[f"{m5_raw:.6f}", 0]])
    w.table("ablationm5norm", ["x", "y"], [[f"{m5_norm:.6f}", 0]])
    w.table("ablationm5res", ["x", "y"], [[f"{m5_res:.6f}", 0]])
    w.macros(
        "ablation",
        {
            "SGablImproved": str(improved),
            "SGablTotal": str(len(names)),
            "SGablRawPooled": f"{rec('scalerag_raw_retrieval'):.3f}",
            "SGablResPooled": f"{rec('scalerag_restored_retrieval'):.3f}",
            "SGablFactor": f"{rec('scalerag_raw_retrieval') / rec('scalerag_restored_retrieval'):.1f}",
            "SGablMfiveRaw": f"{m5_raw:.3f}",
            "SGablMfiveNorm": f"{m5_norm:.3f}",
            "SGablMfiveRes": f"{m5_res:.3f}",
            "SGablMfiveFactor": f"{m5_norm / m5_res:.1f}",
        },
    )
    w.say(
        f"ablation: M5 val raw {m5_raw:.4f}, normalised-unrestored {m5_norm:.4f}, "
        f"restored {m5_res:.4f} ({m5_norm / m5_res:.1f}x)"
    )
    w.say(f"ablation: {improved}/{len(names)} ETTm2 channels improve under restoration")
    w.say(
        f"ablation: pooled {rec('scalerag_raw_retrieval'):.4f} raw -> "
        f"{rec('scalerag_restored_retrieval'):.4f} restored"
    )


# --------------------------------------------------------------- fig_mismatch
def mismatch(w: Writer) -> None:
    r"""One window: what the raw analogue mean looks like, and what restoring it does.

    The figure illustrates the failure mode Section I names "catastrophic
    scale mismatch": a retrieved analogue with the right shape at the wrong
    level, which restoration repairs. So the window is drawn from exactly
    that population -- OT windows where the raw analogue's shape correlation
    with the realised future is >= 0.8 AND restoration reduces the error --
    and within it, the one whose |log| raw-to-true RMS ratio is the median.
    Taking the median of the ratio itself would be the wrong centre, since
    ratios of 2 and 1/2 are the same size of error in opposite directions.

    Both halves of the criterion are needed, and both are exported so the
    caption can say how much of the channel they cover. Keying on RMS alone
    drew a window with shape correlation -0.79 under a caption saying the
    shape was right; keying on shape alone drew one where restoration made
    the error worse under a caption saying it repaired it.
    """
    import sys as _sys

    _sys.path.insert(0, str(REPO / "scripts"))
    import ettm2_data as ettm2

    j = _load("reports/phase11a/scalerag_native_ettm2_test.json")
    names = j["variables"]
    vi = names.index("OT")
    z = np.load(REPO / "reports/phase11a/scalerag_native_ettm2_test_preds.npz")
    trues, var_of, origins = z["trues"], z["var_of"], z["origins"]
    raw, res = z["raw_mean_20"], z["res_mean_20"]

    m = np.flatnonzero(var_of == vi)
    t_win, r_win = trues[m], raw[m]
    # shape agreement, scale-free: Pearson correlation per window
    tc = t_win - t_win.mean(1, keepdims=True)
    rc = r_win - r_win.mean(1, keepdims=True)
    denom = np.sqrt((tc**2).sum(1) * (rc**2).sum(1))
    shape = np.where(denom > 0, (tc * rc).sum(1) / np.maximum(denom, 1e-12), 0.0)
    shape_min = 0.8
    helped = ((res[m] - t_win) ** 2).mean(1) < ((r_win - t_win) ** 2).mean(1)
    good = (shape >= shape_min) & helped
    share_good = float(good.mean())
    share_helped = float(helped.mean())

    rms_t = np.sqrt(np.mean(t_win**2, axis=1))
    rms_r = np.sqrt(np.mean(r_win**2, axis=1))
    ratio = rms_r / np.maximum(rms_t, 1e-12)
    mism = np.abs(np.log(np.maximum(ratio, 1e-12)))  # size of the mismatch, either way
    cand = np.flatnonzero(good)
    order = cand[np.argsort(mism[cand])]
    sel = int(order[len(order) // 2])  # median mismatch among shape-matched windows
    pick = m[sel]
    if shape[sel] < shape_min:
        raise ValueError("selected window fails its own shape criterion")

    ctx_n = 120
    z_all, var_names = ettm2.load_normalized()
    if var_names[vi] != "OT":
        raise ValueError(f"channel order moved: expected OT at {vi}, found {var_names[vi]}")
    # ``origins`` is the global index of the first forecast step, so the
    # context ends at it and the horizon starts at it.
    o = int(origins[pick])
    ctx = z_all[o - ctx_n : o, vi]
    fut = z_all[o : o + ettm2.H, vi]
    if not np.allclose(fut, trues[pick], atol=1e-4):
        raise ValueError("reconstructed future does not match the stored target for this window")

    w.table("mismatchctx", ["t", "y"], [[t - ctx_n, f"{v:.5f}"] for t, v in enumerate(ctx)])
    w.table(
        "mismatch",
        ["t", "true", "raw", "restored"],
        [
            [t, f"{trues[pick][t]:.5f}", f"{raw[pick][t]:.5f}", f"{res[pick][t]:.5f}"]
            for t in range(ettm2.H)
        ],
    )
    w.macros(
        "mismatch",
        {
            "SGmisRatio": f"{ratio[sel]:.2f}",
            # the selection rule keys on RMS, but on this window the damage is
            # mostly LEVEL, which is the paper's finding, so report both
            "SGmisTrueLevel": f"{float(np.mean(trues[pick])):+.2f}",
            "SGmisRawLevel": f"{float(np.mean(raw[pick])):+.2f}",
            "SGmisResLevel": f"{float(np.mean(res[pick])):+.2f}",
            "SGmisPctWorse": f"{100.0 * float(np.mean(mism[cand] > mism[sel])):.0f}",
            "SGmisShape": f"{shape[sel]:.2f}",
            "SGmisShapeMin": f"{shape_min:.1f}",
            "SGmisShareGood": f"{100.0 * share_good:.0f}",
            "SGmisShareHelped": f"{100.0 * share_helped:.0f}",
            "SGmisRawMse": f"{np.mean((raw[pick] - trues[pick]) ** 2):.3f}",
            "SGmisResMse": f"{np.mean((res[pick] - trues[pick]) ** 2):.3f}",
            "SGmisCtx": str(ctx_n),
            # axis range from the data, padded, so a rule that picks a
            # different window cannot leave the drawing clipped
            "SGmisYmin": f"{min(ctx.min(), fut.min(), raw[pick].min(), res[pick].min()) - 0.35:.2f}",
            "SGmisYmax": f"{max(ctx.max(), fut.max(), raw[pick].max(), res[pick].max()) + 0.55:.2f}",
        },
    )
    w.say(
        f"mismatch: OT window at origin {o}, shape corr {shape[sel]:+.2f}, RMS ratio "
        f"{ratio[sel]:.3f}; median of the {100 * share_good:.0f}% of the channel with shape >= "
        f"{shape_min} where restoration helps (it helps on {100 * share_helped:.0f}%)"
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="run every computation, write nothing")
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    w = Writer(a.check)
    for fn in (decomp, band, pareto, metrics, ablation, mismatch):
        fn(w)
    print("\n".join(w.notes))
    print("checked, nothing written" if a.check else f"written to {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
